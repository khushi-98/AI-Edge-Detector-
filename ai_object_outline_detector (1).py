import cv2
import gradio as gr

def edge_detect(image):
    gray = cv2.cvtColor(image, cv2.COLOR_RGB2GRAY)
    edges = cv2.Canny(gray, 100, 200)
    return edges

gr.Interface(
    fn=edge_detect,
    inputs=gr.Image(type="numpy"),
    outputs=gr.Image(),
    title="AI Edge Detector"
).launch()

